// Builds PrimeReact's Elevate Pesa themes: public/themes/lara-{light,dark}-pesa.
//
//   node scripts/build-prime-theme.mjs      (again after any primereact upgrade)
//
// PrimeReact 10's Lara themes hard-code their palette in every rule, so a CSS variable
// override cannot recolour them. This copies Lara Indigo and maps Tailwind's indigo scale
// (which Lara is built on) onto Tailwind's emerald, the Elevate Pesa green.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "node_modules", "primereact", "resources", "themes");

// Tailwind indigo  ->  Elevate Pesa emerald (light): 500 is the primary. Emerald 600 rather than
// 500 so white text on a button stays readable (4.5:1); 700 is its hover.
const light = {
  "#eef2ff": "#ecfdf5",
  "#e0e7ff": "#d1fae5",
  "#c7d2fe": "#a7f3d0",
  "#a5b4fc": "#6ee7b7",
  "#818cf8": "#10b981",
  "#6366f1": "#059669",
  "#4f46e5": "#047857",
  "#4338ca": "#065f46",
  "#3730a3": "#064e3b",
  "#312e81": "#022c22",
  "rgba(99, 102, 241,": "rgba(5, 150, 105,",
};

// Tailwind indigo  ->  emerald (dark): 400 is the primary on a dark page.
const dark = {
  "#eef2ff": "#ecfdf5",
  "#e0e7ff": "#d1fae5",
  "#c7d2fe": "#a7f3d0",
  "#a5b4fc": "#6ee7b7",
  "#818cf8": "#34d399",
  "#6366f1": "#34d399",
  "#4f46e5": "#10b981",
  "#4338ca": "#059669",
  "#3730a3": "#047857",
  "#312e81": "#065f46",
  "rgba(129, 140, 248,": "rgba(52, 211, 153,",
  "rgba(99, 102, 241,": "rgba(52, 211, 153,",
};

function build(from, to, map) {
  const src = join(source, from);
  const out = join(root, "public", "themes", to);
  if (!existsSync(src)) throw new Error(`Missing ${src}: run npm install first.`);

  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(join(src, "fonts"), join(out, "fonts"), { recursive: true });

  let css = readFileSync(join(src, "theme.css"), "utf8");
  for (const [find, replace] of Object.entries(map)) {
    css = css.split(find).join(replace).split(find.toUpperCase()).join(replace);
  }
  writeFileSync(join(out, "theme.css"), `/* Generated by scripts/build-prime-theme.mjs from ${from}. Do not edit. */\n${css}`);
  console.log(`${to}: written`);
}

build("lara-light-indigo", "lara-light-pesa", light);
build("lara-dark-indigo", "lara-dark-pesa", dark);
